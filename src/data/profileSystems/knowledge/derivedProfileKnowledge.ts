export function hasDerivedProfileEvidenceConflict(systemId: string, profileId: string): boolean {
  const signatures = new Set(
    derivedProfileEvidenceRows
      .filter((record) =>
        record.runtimeMappingStatus === 'RUNTIME_MAPPED' &&
        'systemId' in record &&
        record.systemId === systemId &&
        record.profileId === profileId,
      )
      .map((record) => [record.roleBg, record.profileW, record.profileZ, record.catalogue].join('|')),
  )
  return signatures.size > 1
}

