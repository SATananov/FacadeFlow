import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'

const registry = await readFile(new URL('../src/data/profileSystems/technicalSections.ts', import.meta.url), 'utf8')
const graphics = await readFile(new URL('../src/components/assemblyTechnicalSectionGraphics.ts', import.meta.url), 'utf8')
const visualization = await readFile(new URL('../src/domain/systemJointVisualization.ts', import.meta.url), 'utf8')
const productModel = await readFile(new URL('../src/domain/systemDrivenProductModel.ts', import.meta.url), 'utf8')
const panel = await readFile(new URL('../src/components/AssemblyReviewPanel.tsx', import.meta.url), 'utf8')
const acceptance = await readFile(new URL('../docs/ASSEMBLY_FUNCTIONALITY_01A_BOUNDARY_DRIVEN_TECHNICAL_SECTION_RESOLUTION.md', import.meta.url), 'utf8')

assert(registry.includes("TECHNICAL_SECTION_REGISTRY_VERSION = 'technical-section-registry-01'"), 'Technical section registry version missing')
assert(registry.includes("profileCode: '482.30'"), '482.30 technical section missing')
assert(registry.includes("catalogueDepthMm: 60") && registry.includes("catalogueFaceMm: 64"), '482.30 catalogue envelope contract missing')
assert(registry.includes("profileCode: '482.21'"), '482.21 technical section missing')
assert(registry.includes("catalogueFaceMm: 84"), '482.21 catalogue face contract missing')
assert(registry.includes("profileCode: '482.05'"), '482.05 technical section missing')
assert(registry.includes("catalogueFaceMm: 56"), '482.05 catalogue face contract missing')
assert(registry.includes('contourAnchors:'), 'Visual-only contour anchors must live with the technical section')
assert(registry.includes('getTechnicalProfileSection'), 'System + profile technical-section resolver missing')

assert(productModel.includes('systemId: string'), 'Joint read model must carry system identity')
assert(productModel.includes('systemId: system.id,'), 'Resolved joint must receive the selected system identity')

assert(visualization.includes("ASSEMBLY_FUNCTIONALITY_VERSION = 'assembly-functionality-01a'"), 'Assembly functionality version missing')
assert(visualization.includes("getTechnicalProfileSection(systemId, profileCode)"), 'Visualization must resolve registered technical sections')
assert(visualization.includes('sectionSize(joint.systemId, joint.supportProfileCode)'), 'Support section is not system-scoped')
assert(visualization.includes('sectionSize(joint.systemId, joint.sashProfileCode)'), 'Sash section is not system-scoped')
assert(visualization.includes('draftingTemplateKey'), 'Reusable technical drafting key missing')
assert(visualization.includes("technicalSectionStatus: !support || !sash ? 'missing-section' : 'missing-rule'"), 'Fail-closed section/rule status missing')
assert(visualization.includes('FacadeFlow не създава заместителна геометрия'), 'Missing-section fail-closed message missing')
assert(!visualization.includes('const PROFILE_SECTION_SIZES'), 'Profile section sizes must no longer be a visualization-local hardcoded map')

assert(graphics.includes("'prelude60-frame-48230'"), '482.30 graphic registry entry missing')
assert(graphics.includes("'prelude60-mullion-48221'"), '482.21 graphic registry entry missing')
assert(graphics.includes("'prelude60-sash-48205'"), '482.05 graphic registry entry missing')
assert(graphics.includes('prelude60-48230-frame-assembly.png'), '482.30 assembly graphic missing')
assert(graphics.includes('prelude60-48221-mullion-assembly.png'), '482.21 assembly graphic missing')
assert(graphics.includes('prelude60-48205-sash-assembly.png'), '482.05 assembly graphic missing')

assert(panel.includes('getTechnicalProfileSection(joint.systemId, joint.supportProfileCode)'), 'Panel must resolve support section from system data')
assert(panel.includes('getTechnicalProfileSection(joint.systemId, joint.sashProfileCode)'), 'Panel must resolve sash section from system data')
assert(panel.includes('getAssemblyTechnicalSectionGraphic(supportTechnicalSection'), 'Support assembly graphic must come from graphic registry')
assert(panel.includes('getAssemblyTechnicalSectionGraphic(sashTechnicalSection'), 'Sash assembly graphic must come from graphic registry')
assert(panel.includes('section?.contourAnchors'), 'Identity callout contour anchors must come from section data')
assert(!panel.includes("import frame48230AssemblyImage from '../assets/catalog/prelude60/prelude60-48230-frame-assembly.png'"), 'Panel must not import pair-specific assembly graphics directly')
assert(panel.includes('className="assembly-auto-reference-value is-fix49"'), 'FIX49 system-correction annotation must remain')

assert(acceptance.includes('Frame 482.30 <-> Sash 482.05'), 'Frame/sash supported family not documented')
assert(acceptance.includes('Mullion 482.21 <-> Sash 482.05'), 'Mullion/sash supported family not documented')
assert(acceptance.includes('AUTOMATIC GEOMETRY = NO'), 'Automatic geometry safety boundary missing')
assert(acceptance.includes('RULES VALIDATED = NO'), 'Rules validation safety boundary missing')
assert(acceptance.includes('PRODUCTION AUTO-UNLOCK = NO'), 'Production safety boundary missing')
assert(acceptance.includes('MACHINE READY = NO'), 'Machine readiness safety boundary missing')

