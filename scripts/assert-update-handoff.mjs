// Source checks complement the real Windows parent-exit survival test.
export function assertUpdateHandoffContract({ main, read, fail }) {
  const handoff = read('electron/updateHandoff.mjs')
  const bootstrap = read('electron/update-bootstrap.ps1')
  const worker = read('electron/update-worker.ps1')
  const required = (source, text, message) => { if (!source.includes(text)) fail(message) }
  required(main, 'handoff = await prepareWindowsUpdateHandoff({', 'main must await independent worker readiness')
  required(main, 'await handoff.authorize()', 'main authorization missing')
  const prepared = main.indexOf('handoff = await prepareWindowsUpdateHandoff({')
  const authorized = main.indexOf('await handoff.authorize()', prepared)
  const quit = main.indexOf('setTimeout(() => app.quit(), 100)', prepared)
  if (!(prepared < authorized && authorized < quit)) fail('quit must follow readiness and authorization')
  required(main, 'await handoff?.cancel()', 'failed handoff must cancel the worker')
  required(main, 'installInProgress', 'concurrent installer handoff guard missing')
  required(handoff, 'detached: false', 'bootstrap must use the working non-detached spawn mode')
  if (handoff.includes('detached: true') || handoff.includes('.unref()')) fail('unproven detached/unref lifetime mechanism returned')
  required(handoff, 'windowsHide: true', 'bootstrap window must stay hidden')
  required(handoff, "process.env.SystemRoot || process.env.WINDIR || 'C:\\\\Windows'", 'explicit Windows PowerShell resolution missing')
  required(handoff, "'System32', 'WindowsPowerShell', 'v1.0', 'powershell.exe'", 'canonical PowerShell path missing')
  required(handoff, "child.once('error', (error) =>", 'spawn error capture missing')
  required(handoff, "child.once('exit', (code, signal) =>", 'bootstrap exit capture missing')
  required(handoff, 'Update bootstrap failed to start:', 'spawn failure must be surfaced')
  required(handoff, 'Update bootstrap exited before readiness:', 'early exit must be surfaced')
  required(handoff, 'Update bootstrap did not acknowledge startup in time', 'bounded readiness wait missing')
  required(handoff, 'randomUUID()', 'unique transaction identity missing')
  required(handoff, 'copyFile(', 'scripts must survive app.asar replacement')
  required(handoff, "'worker-ready.json'", 'worker READY missing')
  required(handoff, "'bootstrap-ack.json'", 'independent worker acknowledgement missing')
  required(handoff, 'ready.token !== token || ack.token !== token', 'stale/foreign acknowledgement rejection missing')
  required(handoff, 'ack.workerPid !== ready.workerPid', 'worker identity check missing')
  required(handoff, 'process.kill(ready.workerPid, 0)', 'worker liveness check after bootstrap exit missing')
  required(handoff, "'worker-authorized.json'", 'worker authorization acknowledgement wait missing')
  required(handoff, "await rename(authorizeTemp, authorizePath)", 'authorization marker must be published atomically')
  required(handoff, 'Update worker did not acknowledge authorization in time', 'authorization acknowledgement timeout missing')
  required(bootstrap, 'Invoke-CimMethod -ClassName Win32_Process -MethodName Create', 'Windows provider worker creation missing')
  required(bootstrap, 'ShowWindow=[uint16]0', 'worker window must stay hidden')
  required(bootstrap, '$created.ReturnValue -ne 0', 'Windows creation failure must reject handoff')
  required(bootstrap, '$ready.workerStartTicks -ne $worker.StartTime', 'worker process identity verification missing')
  required(bootstrap, '$ready.sessionId -ne $parent.SessionId', 'interactive session guard missing')
  required(worker, "Write-Record 'worker-ready.json'", 'worker readiness signal missing')
  required(worker, "'authorize.flag'", 'explicit install authorization gate missing')
  required(worker, "Write-Record 'worker-authorized.json'", 'worker authorization acknowledgement missing')
  required(worker, "'cancel.flag'", 'worker cancellation gate missing')
  required(worker, 'while (Test-ParentAlive)', 'worker must wait for original parent')
  required(worker, '$candidate.StartTime.ToUniversalTime().Ticks', 'parent PID reuse guard missing')
  required(worker, "if ($request.mode -eq 'probe')", 'harmless survival mode missing')
  required(worker, 'FacadeFlow-Update-', 'worker canonical filename check missing')
  required(worker, '$installerInfo.Length -ne $request.expectedBytes', 'worker size recheck missing')
  required(worker, 'Get-FileHash -LiteralPath $InstallerPath -Algorithm SHA256', 'worker SHA-256 recheck missing')
  required(worker, '$stream.ReadByte() -ne 0x4d', 'worker MZ recheck missing')
  required(worker, "-ArgumentList '/S' -WindowStyle Hidden -PassThru -Wait", 'silent installer must be awaited')
  required(worker, '$installer.ExitCode -ne 0', 'installer exit validation missing')
  required(worker, '$versionMatches = $installedNumericVersion -eq $expectedNumericVersion', 'installed version validation missing')
  required(worker, 'Start-Process -FilePath $RelaunchPath -PassThru', 'verified installed app relaunch missing')
  if (worker.includes('Start-Process -FilePath $RelaunchPath -WindowStyle Hidden')) fail('relaunched GUI must not be forced hidden')
  const parentWait = worker.indexOf('while (Test-ParentAlive)')
  const install = worker.indexOf('$installer = Start-Process')
  const versionCheck = worker.indexOf('$versionMatches =')
  const relaunch = worker.indexOf('$relaunched = Start-Process')
  if (!(parentWait < install && install < versionCheck && versionCheck < relaunch)) fail('wait/install/verify/relaunch ordering changed')
}
